//! Calculator keys.

use serde::{Deserialize, Serialize};

/// One calculator key, in keypad layout order (top to bottom, left to right).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
pub enum KeyId {
    YEqu,
    Window,
    Zoom,
    Trace,
    Graph,
    Second,
    Mode,
    Del,
    Up,
    Left,
    Right,
    Down,
    Alpha,
    XTThetaN,
    Stat,
    Math,
    Apps,
    Prgm,
    Vars,
    Clear,
    Inverse,
    Sin,
    Cos,
    Tan,
    Power,
    Square,
    Comma,
    LParen,
    RParen,
    Div,
    Log,
    Seven,
    Eight,
    Nine,
    Mul,
    Ln,
    Four,
    Five,
    Six,
    Sub,
    Sto,
    One,
    Two,
    Three,
    Add,
    On,
    Zero,
    Dot,
    Neg,
    Enter,
}

impl KeyId {
    /// Every key, in layout order.
    pub const ALL: [KeyId; 50] = [
        KeyId::YEqu,
        KeyId::Window,
        KeyId::Zoom,
        KeyId::Trace,
        KeyId::Graph,
        KeyId::Second,
        KeyId::Mode,
        KeyId::Del,
        KeyId::Up,
        KeyId::Left,
        KeyId::Right,
        KeyId::Down,
        KeyId::Alpha,
        KeyId::XTThetaN,
        KeyId::Stat,
        KeyId::Math,
        KeyId::Apps,
        KeyId::Prgm,
        KeyId::Vars,
        KeyId::Clear,
        KeyId::Inverse,
        KeyId::Sin,
        KeyId::Cos,
        KeyId::Tan,
        KeyId::Power,
        KeyId::Square,
        KeyId::Comma,
        KeyId::LParen,
        KeyId::RParen,
        KeyId::Div,
        KeyId::Log,
        KeyId::Seven,
        KeyId::Eight,
        KeyId::Nine,
        KeyId::Mul,
        KeyId::Ln,
        KeyId::Four,
        KeyId::Five,
        KeyId::Six,
        KeyId::Sub,
        KeyId::Sto,
        KeyId::One,
        KeyId::Two,
        KeyId::Three,
        KeyId::Add,
        KeyId::On,
        KeyId::Zero,
        KeyId::Dot,
        KeyId::Neg,
        KeyId::Enter,
    ];

    /// The key's visible main label (for the D-pad: its accessibility label).
    pub fn name(self) -> &'static str {
        match self {
            KeyId::YEqu => "y=",
            KeyId::Window => "window",
            KeyId::Zoom => "zoom",
            KeyId::Trace => "trace",
            KeyId::Graph => "graph",
            KeyId::Second => "2nd",
            KeyId::Mode => "mode",
            KeyId::Del => "del",
            KeyId::Up => "up",
            KeyId::Left => "left",
            KeyId::Right => "right",
            KeyId::Down => "down",
            KeyId::Alpha => "alpha",
            KeyId::XTThetaN => "X,T,\u{3B8},n",
            KeyId::Stat => "stat",
            KeyId::Math => "math",
            KeyId::Apps => "apps",
            KeyId::Prgm => "prgm",
            KeyId::Vars => "vars",
            KeyId::Clear => "clear",
            KeyId::Inverse => "x\u{207B}\u{B9}",
            KeyId::Sin => "sin",
            KeyId::Cos => "cos",
            KeyId::Tan => "tan",
            KeyId::Power => "^",
            KeyId::Square => "x\u{B2}",
            KeyId::Comma => ",",
            KeyId::LParen => "(",
            KeyId::RParen => ")",
            KeyId::Div => "\u{F7}",
            KeyId::Log => "log",
            KeyId::Seven => "7",
            KeyId::Eight => "8",
            KeyId::Nine => "9",
            KeyId::Mul => "\u{D7}",
            KeyId::Ln => "ln",
            KeyId::Four => "4",
            KeyId::Five => "5",
            KeyId::Six => "6",
            KeyId::Sub => "\u{2212}",
            KeyId::Sto => "sto\u{2192}",
            KeyId::One => "1",
            KeyId::Two => "2",
            KeyId::Three => "3",
            KeyId::Add => "+",
            KeyId::On => "on",
            KeyId::Zero => "0",
            KeyId::Dot => ".",
            KeyId::Neg => "(\u{2212})",
            KeyId::Enter => "enter",
        }
    }
}
